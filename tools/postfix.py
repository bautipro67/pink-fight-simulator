"""Hand fixes applied to the machine-translated Pink modules after tools/gml2js_obj.py (so the
translation can be regenerated by tools/gen_pink.sh): python -I tools/postfix.py <module.js>

Edit this file, never src/pink/gen/*.js."""
import os, re, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
p = sys.argv[1]
t = open(p, encoding='utf-8').read()

# Battle-module scripts (on S) that take the calling instance first, as the GML runs them in its scope.
CALLER_FIRST = [
    'draw_monster_body_part', 'scr_bulletspawner', 'scr_damage', 'scr_damage_all', 'scr_damage_maxhp',
    'scr_enemy_drawidle_generic', 'scr_enemy_hurt', 'scr_enemy_object_init', 'scr_healitemspell',
    'scr_healallitemspell', 'scr_monstersetup', 'scr_monsterdefeat', 'scr_randomtarget', 'scr_randomtarget_old',
    'scr_retarget', 'scr_retarget_spell', 'scr_spell', 'scr_spelltext', 'scr_targetall', 'scr_afterimage',
    'scr_oflash', 'scr_spareanim', 'scr_battletext_default', 'scr_enemyblcon', 'scr_blconskip', 'scr_simultext',
    'scr_rememberxy', 'scr_move_to_rememberxy', 'position_meeting', 'scr_monster_setup_default',
    'scr_move_to_point_over_time',
]
for name in CALLER_FIRST:
    # (the translator already passes `this` to some of them)
    t = re.sub(r'\bS\.%s\((?!this\b)' % name, 'S.%s(this, ' % name, t)
    t = t.replace('S.%s(this, )' % name, 'S.%s(this)' % name)
# The translator's injected caller leaves a double space: `f(this,  x)`.
t = t.replace('(this,  ', '(this, ')

# Anything else left to S that the engine or src/pink/common.js exports is called directly (with the
# caller first when the export takes `self` first). Scripts the battle modules define stay on S.
exports = {}
for f in ('src/runtime/gm.js', 'src/runtime/audio.js', 'src/pink/common.js'):
    src = open(os.path.join(ROOT, f), encoding='utf-8').read()
    for name, params in re.findall(r'export (?:async )?function (\w+)\(([^)]*)\)', src):
        exports[name] = params.split(',')[0].strip() == 'self'
    for name, params, single in re.findall(r'export const (\w+) = (?:\(([^)]*)\)|(\w+)) =>', src):
        exports[name] = (params or single or '').split(',')[0].strip() == 'self'


def direct(m):
    name = m.group(1)
    if name not in exports:
        return m.group(0)
    return name + ('(this, ' if exports[name] else '(')


t = re.sub(r'\bS\.(\w+)\(', direct, t)
t = t.replace('(this, )', '(this)')
# `other` outside a with, in an ordinary event, is the instance itself.
t = t.replace('G.other.', 'this.')

# obj_pink_enemy Create: drop_petal = method(-1, anon...) -> a method of the class (see dropPetal).
t = re.sub(r"    this\.drop_petal = S\.method\([^;]*\);\n", "", t)
t = t.replace('S.drop_petal(', 'this.dropPetal(')


def add_method(cls_obj, cls_name, code):
    """Adds code (methods) at the end of a translated class."""
    global t
    m = re.search(r"defineObject\('%s', %s\);" % (cls_obj, cls_name), t)
    if not m:
        return
    end = t.rfind('}', 0, m.start())
    t = t[:end] + code + t[end:]


add_method('obj_pink_enemy', 'PinkEnemy', """  // drop_petal(x, y, ...): a spin petal falling behind the battle box (obj_marker_doomed, gone after
  // 120 frames), with its constructor struct's values.
  dropPetal(x, y) {
    if (!i_ex('obj_battlecontroller')) return;
    const p = instance_create_depth(x, y, O('obj_battlecontroller').depth + 1, 'obj_marker_doomed');
    Object.assign(p, { image_xscale: 2, image_yscale: 2, sprite_index: 'spr_spin_petal', image_speed: random(0.2) + 0.1,
      gravity_direction: 175 + random(10), vspeed: 5, hspeed: -2, gravity: 0.06, image_blend: merge_color(0xffffff, 0, random(0.25)) });
    p.alarm[0] = 120;
  }
""")

open(p, 'w', encoding='utf-8', newline='').write(t)

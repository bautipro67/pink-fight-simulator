"""Hand fixes applied to the machine-translated Pink modules after tools/gml2js_obj.py (so the
translation can be regenerated by tools/gen_pink.sh): python -I tools/postfix.py <module.js>

Edit this file, never src/pink/gen/*.js."""
import os, re, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
p = sys.argv[1]
t = open(p, encoding='utf-8').read()

# Every while / do-until loop also calls LOOP(id) (src/pink/gml.js), which stops a runaway loop with an
# error naming it (the class it is in and its number there) instead of freezing the page.
_loops = [0]


def _guard(cond):
    _loops[0] += 1
    cls = re.findall(r'(?m)^class (\w+)', t[:_pos[0]])
    return '(%s) && LOOP(%s)' % (cond, repr('%s#%d' % (cls[-1] if cls else '?', _loops[0])))


_pos = [0]
out, last = [], 0
for m in re.finditer(r'(?m)^(\s*)(\} while|while) \((.*)\)( \{|;)$', t):
    _pos[0] = m.start()
    out.append(t[last:m.start()])
    out.append('%s%s (%s)%s' % (m.group(1), m.group(2), _guard(m.group(3)), m.group(4)))
    last = m.end()
out.append(t[last:])
t = ''.join(out)

# Battle-module scripts (on S) that take the calling instance first, as the GML runs them in its scope.
CALLER_FIRST = [
    'draw_monster_body_part', 'scr_bulletspawner', 'scr_damage', 'scr_damage_all', 'scr_damage_maxhp',
    'scr_enemy_drawidle_generic', 'scr_enemy_hurt', 'scr_enemy_object_init', 'scr_healitemspell',
    'scr_healallitemspell', 'scr_monstersetup', 'scr_monsterdefeat', 'scr_randomtarget', 'scr_randomtarget_old',
    'scr_retarget', 'scr_retarget_spell', 'scr_spell', 'scr_spelltext', 'scr_targetall', 'scr_afterimage',
    'scr_oflash', 'scr_spareanim', 'scr_battletext_default', 'scr_enemyblcon', 'scr_blconskip', 'scr_simultext',
    'scr_rememberxy', 'scr_move_to_rememberxy', 'position_meeting', 'scr_monster_setup_default',
    'scr_move_to_point_over_time', 'scr_shakescreen', 'snd_play_delayed',
]
for name in CALLER_FIRST:
    # (the translator already passes `this` to some of them)
    t = re.sub(r'\bS\.%s\((?!this\b)' % name, 'S.%s(this, ' % name, t)
    t = t.replace('S.%s(this, )' % name, 'S.%s(this)' % name)
# The translator's injected caller leaves a double space: `f(this,  x)`.
t = t.replace('(this,  ', '(this, ')

# Anything else left to S that the engine or src/pink/common.js exports is called directly (with the
# caller first when the export takes `self` first). Scripts the battle modules define stay on S.
exports = {}
for f in ('src/runtime/gm.js', 'src/runtime/audio.js', 'src/pink/common.js'):
    src = open(os.path.join(ROOT, f), encoding='utf-8').read()
    for name, params in re.findall(r'export (?:async )?function (\w+)\(([^)]*)\)', src):
        exports[name] = params.split(',')[0].strip() == 'self'
    for name, params, single in re.findall(r'export const (\w+) = (?:\(([^)]*)\)|(\w+)) =>', src):
        exports[name] = (params or single or '').split(',')[0].strip() == 'self'


def direct(m):
    name = m.group(1)
    if name not in exports:
        return m.group(0)
    return name + ('(this, ' if exports[name] else '(')


t = re.sub(r'\bS\.(\w+)\(', direct, t)
t = t.replace('(this, )', '(this)')
# `other` outside a with, in an ordinary event, is the instance itself.
t = t.replace('G.other.', 'this.')
# The one camera (view_camera[0] is GML's built-in array, not an instance variable).
t = t.replace('this.view_camera[0]', '0')
# A collision / instance_place result is an instance or noone (-4) in GML, compared with 0 or -4; here it
# is an instance or null (and `null >= 0` is true), so those comparisons become existence checks.
for v in set(re.findall(r'\b(\w+) = (?:collision_\w+|instance_place|instance_position|instance_nearest)\(', t)):
    t = re.sub(r'\b%s (>=|>) 0\b' % v, '%s != null' % v, t)
    t = re.sub(r'\b%s (<|<=) 0\b' % v, '%s == null' % v, t)
    t = re.sub(r'\b%s != - ?4\b' % v, '%s != null' % v, t)
    t = re.sub(r'\b%s == - ?4\b' % v, '%s == null' % v, t)
# event_perform(ev_alarm, n) runs the instance's alarm n.
t = re.sub(r'S\.event_perform\(2, (\d+)\)', r'this.alarm\1?.()', t)
# event_perform(ev_draw, 0) draws the instance now.
t = t.replace('S.event_perform(8, 0)', 'this.draw?.()')
# The engine's instance_place takes the instance first (as place_meeting, which the translator handles).
t = re.sub(r'\binstance_place\((?!this, )', 'instance_place(this, ', t)
# Caller-scope scripts the Chapter 5 objects call.
t = re.sub(r'\bS\.distance_to_object\(', 'S.distance_to_object(this, ', t)
# Sub-image -1 in a draw is the drawing instance's own image_index (the engine would take the last frame).
t = re.sub(r'\b(draw_sprite\w*)\(([^,()]+(?:\([^()]*\))?), - ?1,', r'\1(\2, this.image_index,', t)

# Sprite indices the decompiler left bare (no /*spr_x*/ note) in sprite variables (the date's portraits):
# named from research/names.json (tools/dump_names.py).
import json
_names = json.load(open(os.path.join(ROOT, 'research', 'names.json')))
# (also a random pick: pinkportrait = choose(6755, 677, 2038))
t = re.sub(r'\b((?:this\.)?\w*(?:portrait\d?|_spr|sprite|sprite_index)) = choose\(([\d, ]+)\);',
           lambda m: "%s = choose(%s);" % (m.group(1), ', '.join("'%s'" % _names['sprites'][int(n)] for n in m.group(2).split(','))), t)
t = re.sub(r'\b((?:this\.)?\w*(?:portrait\d?|_spr|sprite|sprite_index)) = (\d{2,4});',
           lambda m: "%s = '%s';" % (m.group(1), _names['sprites'][int(m.group(2))]) if int(m.group(2)) < len(_names['sprites']) else m.group(0), t)

# obj_pinknode Create: fnc_make_node = method(self, ...): a child node at dir * 90 degrees, dist away.
t = re.sub(r"this\.fnc_make_node = S\.method\([^;]*\);",
           "this.fnc_make_node = (dir, dist) => { this.child ??= []; this.child[dir] = instance_create_depth("
           "this.x + lengthdir_x(dist, dir * 90), this.y + lengthdir_y(dist, dir * 90), this.depth, 'obj_pinknode'); "
           "return this.child[dir]; };", t)
t = t.replace('S.fnc_make_node(', 'this.fnc_make_node(')
# obj_pink_tension_glow Create: draw_w_offset only sets its own locals (does nothing).
t = re.sub(r"this\.draw_w_offset = S\.method\([^;]*\);", "this.draw_w_offset = () => {};", t)
t = t.replace('S.draw_w_offset(', 'this.draw_w_offset(')

# obj_pink_enemy Create: drop_petal = method(-1, anon...) -> a method of the class (see dropPetal).
t = re.sub(r"    this\.drop_petal = S\.method\([^;]*\);\n", "", t)
t = t.replace('S.drop_petal(', 'this.dropPetal(')


def add_method(cls_obj, cls_name, code):
    """Adds code (methods) at the end of a translated class."""
    global t
    m = re.search(r"defineObject\('%s', %s\);" % (cls_obj, cls_name), t)
    if not m:
        return
    end = t.rfind('}', 0, m.start())
    t = t[:end] + code + t[end:]


add_method('obj_pink_enemy', 'PinkEnemy', """  // drop_petal(x, y, ...): a spin petal falling behind the battle box (obj_marker_doomed, gone after
  // 120 frames), with its constructor struct's values.
  dropPetal(x, y) {
    if (!i_ex('obj_battlecontroller')) return;
    const p = instance_create_depth(x, y, O('obj_battlecontroller').depth + 1, 'obj_marker_doomed');
    Object.assign(p, { image_xscale: 2, image_yscale: 2, sprite_index: 'spr_spin_petal', image_speed: random(0.2) + 0.1,
      gravity_direction: 175 + random(10), vspeed: 5, hspeed: -2, gravity: 0.06, image_blend: merge_color(0xffffff, 0, random(0.25)) });
    p.alarm[0] = 120;
  }
""")

open(p, 'w', encoding='utf-8', newline='').write(t)
